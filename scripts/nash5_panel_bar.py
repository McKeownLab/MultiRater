"""Paired statistics for the "Nash, all five raters" bar in Figure 2b.

Reuses the exact code path of figures/fig2_results.py (same OOF files, rows, folds,
seeds, scoring against R1-R3, and the same 400 paired subject resamples), so these numbers are
consistent with the other Figure 2b bars. No models are trained.

Inputs: results/tables/dedup_multiseed/p1_dedup_seed*.csv (five-rater arms) and
        r123_dedup_seed*.csv (R1-R3 arms).
Usage:  python scripts/nash5_panel_bar.py
Writes: results/tables/nash5_panel_bar.md
"""
from __future__ import annotations

import ast
import hashlib
import json
import re
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "figures"))
import fig2_results as f2  # noqa: E402

OUT = ROOT / "results" / "tables" / "nash5_panel_bar.md"
EXPECTED = {"Nash 5 raters": 0.611, "Consensus 5 raters": 0.571, "Nash R1–R3": 0.594}


def nash_kwargs() -> dict:
    src = (ROOT / "utils" / "settings.py").read_text(encoding="utf-8")
    consts = {k: ast.literal_eval(v) for k, v in re.findall(r"^(N_EPOCHS|LR|DISAGREEMENT_WEIGHT_SCALE)\s*=\s*(\S+)", src, re.M)}
    consts["NASH_KWARGS"] = ast.literal_eval(re.search(r"^NASH_KWARGS\s*=\s*(\{.*?\})", src, re.M).group(1))
    trainer = (ROOT / "utils" / "nash_training.py").read_text(encoding="utf-8")
    consts["loss_ema_decay"] = 0.9 if "0.9 * loss_ema_sub + 0.1 * losses" in trainer else None
    return consts


def main():
    p1 = f2.load("p1_dedup_seed*.csv")
    r3 = f2.load("r123_dedup_seed*.csv")
    keys = r3["consensus"][0][f2.KEY]
    labels = keys.merge(p1["consensus_mean"][0][f2.KEY + ["subject_id"] + [f"{p}_{r}" for p in "ym" for r in f2.ALL5]],
                        on=f2.KEY, how="left")

    def restrict(frames):
        return [keys.merge(f, on=f2.KEY, how="left") for f in frames]

    def relabel(frames):
        return [labels.merge(f[f2.KEY + ["fold", "y_pred"]], on=f2.KEY, how="left") for f in frames]

    frames = {
        "Consensus 5 raters": restrict(p1["consensus_mean"]),
        "Consensus R1–R3": relabel(r3["consensus"]),
        "Nash R1–R3": relabel(r3["nash"]),
        "Nash 5 raters": restrict(p1["nash"]),
    }
    seeds = {
        "Consensus 5 raters": [int(f["seed"].iloc[0]) for f in p1["consensus_mean"]],
        "Nash 5 raters": [int(f["seed"].iloc[0]) for f in p1["nash"]],
        "Consensus R1–R3": [int(f["seed"].iloc[0]) for f in r3["consensus"]],
        "Nash R1–R3": [int(f["seed"].iloc[0]) for f in r3["nash"]],
    }

    # Verification: identical rows, folds and seeds for every bar.
    checks = []
    ref = frames["Consensus 5 raters"][0]
    same_rows = all(len(f) == len(keys) and (f[f2.KEY].values == ref[f2.KEY].values).all() and f["y_pred"].notna().all()
                    for fr in frames.values() for f in fr)
    same_folds = all((f["fold"].to_numpy() == ref["fold"].to_numpy()).all() for fr in frames.values() for f in fr)
    same_seeds = len({tuple(v) for v in seeds.values()}) == 1
    checks += [("identical 1,547 rows in every arm and seed", same_rows and len(keys) == 1547),
               ("identical fold assignment", same_folds),
               (f"identical seed list {seeds['Nash 5 raters']}", same_seeds)]

    res = f2.evaluate({n: f2.Arm(fr, f2.R123) for n, fr in frames.items()}, labels["subject_id"].to_numpy(),
                      "Consensus 5 raters")
    arms = res["arms"]
    for name, exp in EXPECTED.items():
        checks.append((f"{name} κ = {arms[name]['kappa']:.3f} (expected {exp:.3f})", abs(arms[name]["kappa"] - exp) <= 0.002))

    d_nc = f2.pair(res, "Nash 5 raters", "Consensus 5 raters")
    d_nn = f2.pair(res, "Nash 5 raters", "Nash R1–R3")
    checks.append((f"Nash5 − Consensus5 Δ = {d_nc['delta']:+.3f} (expected ≈ +0.040)", abs(d_nc["delta"] - 0.040) <= 0.005))

    cfg = nash_kwargs()
    ok_kwargs = cfg["NASH_KWARGS"] == {"min_weight": 0.1, "weight_ema": 0.8, "warmup_epochs": 40} \
        and cfg.get("LR") == 0.01 and cfg.get("N_EPOCHS") == 300 and cfg.get("DISAGREEMENT_WEIGHT_SCALE") == 2.5 \
        and cfg.get("loss_ema_decay") == 0.9
    checks.append((f"training settings {cfg}", ok_kwargs))

    fold_map = ref[["session_id", "fold"]].drop_duplicates().sort_values("session_id")
    cfg_blob = json.dumps(cfg, sort_keys=True) + fold_map.to_csv(index=False)
    cfg_hash = hashlib.sha256(cfg_blob.encode("utf-8")).hexdigest()

    def fci(ci):
        return f2.fci(*ci)  # same CI formatting as Figure 2

    lines = [
        "# Figure 2b: Nash trained on all five raters",
        "",
        "Generated by `scripts/nash5_panel_bar.py`. It uses the same out-of-fold predictions, rows, folds, seeds,",
        "R1–R3 scoring and paired bootstrap as `figures/fig2_results.py`. No models were retrained.",
        "",
        f"Rows: {len(keys):,}, the rows scored by all of R1–R3 ({labels['subject_id'].nunique()} subjects), scored against R1–R3.",
        "",
        "## a) Arms",
        "",
        "| Arm | Mean κ (5 seeds) | 95% CI | Per-seed κ |",
        "|---|---:|---|---|",
    ]
    for name in ("Consensus 5 raters", "Consensus R1–R3", "Nash R1–R3", "Nash 5 raters"):
        a = arms[name]
        lines.append(f"| {name} | {a['kappa']:.3f} | {fci(a['ci95'])} | {', '.join(f'{v:.3f}' for v in a['kappa_per_seed'])} |")
    lines += [
        "",
        "## b) Paired differences (same subject resamples for both arms)",
        "",
        "| Contrast | Δκ | 95% CI | Seeds with Δ > 0 |",
        "|---|---:|---|---|",
        f"| Nash 5 raters − Consensus 5 raters | {d_nc['delta']:+.3f} | {fci(d_nc['ci95'])} | {d_nc['seeds_positive']} of {d_nc['n_seeds']} |",
        f"| Nash 5 raters − Nash R1–R3 | {d_nn['delta']:+.3f} | {fci(d_nn['ci95'])} | {d_nn['seeds_positive']} of {d_nn['n_seeds']} |",
        "",
        "## c) Seed wins",
        "",
        f"Nash (5 raters) exceeds Consensus (5 raters) in **{d_nc['seeds_positive']} of {d_nc['n_seeds']}** seeds.",
        "",
        "## d) Settings",
        "",
        f"- Seeds: {seeds['Nash 5 raters']}. Bootstrap: {f2.N_BOOT} subject resamples, generator seed {f2.BOOT_SEED}; κ averaged over seeds within each resample.",
        f"- Training settings, read from code: {cfg}",
        f"- Config hash, sha256 of the settings plus the session→fold map: `{cfg_hash}`",
        "",
        "## Verification",
        "",
    ]
    lines += [f"- {'PASS' if ok else 'FAIL'}: {msg}" for msg, ok in checks]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    OUT.with_suffix(".json").write_text(json.dumps({
        "arms": {n: {"kappa": a["kappa"], "ci95": a["ci95"], "kappa_per_seed": a["kappa_per_seed"]} for n, a in arms.items()},
        "nash5_minus_consensus5": d_nc,
        "nash5_minus_nash_r123": d_nn,
        "seeds": seeds["Nash 5 raters"], "n_boot": f2.N_BOOT, "boot_seed": f2.BOOT_SEED, "config_hash": cfg_hash,
        "checks_passed": all(ok for _, ok in checks),
    }, indent=2, ensure_ascii=False), encoding="utf-8")
    print("\n".join(lines))
    if not all(ok for _, ok in checks):
        raise SystemExit("verification failed")


if __name__ == "__main__":
    main()
